// 通过 CDP 的 Network.getAllCookies 导出指定域的全部 cookie（含 HttpOnly）为 Netscape cookies.txt
// 供 yt-dlp --cookies 使用。自包含：仅依赖 Node 22+ 内置的 fetch 与全局 WebSocket。
//
// 用法:
//   node export_cookies.mjs <输出路径> <cdp端口> [域过滤词]
// 例:
//   node export_cookies.mjs ./cookies.txt 9223 douyin
//
// 原理: 让运行中的 Chrome 进程自己吐出明文 cookie，
// 绕过 Chrome 127+ 的 App-Bound Encryption (ABE) 文件加密 ——
// yt-dlp 的 --cookies-from-browser 因无法解密该文件而失败，本脚本不经文件读取。

import { writeFileSync } from 'node:fs';

const outPath = process.argv[2];
const port = process.argv[3] || '9222';
const domainFilter = process.argv[4] || ''; // 例如 'douyin'，留空则导出全部
const CDP = `http://localhost:${port}`;

if (!outPath) {
  console.error('用法: node export_cookies.mjs <输出路径> <cdp端口> [域过滤词]');
  process.exit(1);
}

if (typeof WebSocket === 'undefined') {
  console.error('当前 Node 不支持全局 WebSocket，请使用 Node 22 或更高版本。');
  process.exit(1);
}

// 1. 取页面列表，优先选含域过滤词的 page
const res = await fetch(`${CDP}/json`);
if (!res.ok) {
  console.error(`无法连接 CDP (${CDP}/json)：${res.status} ${res.statusText}。请确认 cdp-cli launch 已启动调试 Chrome。`);
  process.exit(1);
}
const pages = await res.json();
const page =
  pages.find(p => p.type === 'page' && (!domainFilter || p.url.includes(domainFilter))) ||
  pages.find(p => p.type === 'page');
if (!page) {
  console.error('未找到可用的页面 target。请先用 cdp-cli new 打开目标站点。');
  process.exit(1);
}

// 2. 连接页面 WebSocket
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id = 0;
const pending = new Map();
ws.addEventListener('message', (ev) => {
  const msg = JSON.parse(typeof ev.data === 'string' ? ev.data : ev.data.toString());
  if (msg.id && pending.has(msg.id)) {
    const { resolve, reject } = pending.get(msg.id);
    pending.delete(msg.id);
    if (msg.error) reject(new Error(msg.error.message || 'CDP error'));
    else resolve(msg.result);
  }
});
function send(method, params = {}) {
  return new Promise((resolve, reject) => {
    const myId = ++id;
    pending.set(myId, { resolve, reject });
    ws.send(JSON.stringify({ id: myId, method, params }));
  });
}

await new Promise((resolve, reject) => {
  ws.addEventListener('open', resolve, { once: true });
  ws.addEventListener('error', reject, { once: true });
});

// 3. Network.getAllCookies 拿全部 cookie（含 HttpOnly），再按域过滤
await send('Network.enable', {});
const { cookies } = await send('Network.getAllCookies', {});
const picked = cookies.filter(c => c.domain && (!domainFilter || c.domain.includes(domainFilter)));

// 4. 写 Netscape cookies.txt
let out = '# Netscape HTTP Cookie File\n# Generated by video-digest skill (export_cookies.mjs)\n';
for (const c of picked) {
  const domain = c.domain;
  const subdomains = domain.startsWith('.') ? 'TRUE' : 'FALSE';
  const path = c.path || '/';
  const secure = c.secure ? 'TRUE' : 'FALSE';
  const exp =
    typeof c.expires === 'number' && c.expires > 0
      ? c.expires
      : Math.floor(Date.now() / 1000) + 86400; // session cookie 给一天有效期
  out += `${domain}\t${subdomains}\t${path}\t${secure}\t${exp}\t${c.name}\t${c.value}\n`;
}
writeFileSync(outPath, out, 'utf-8');
console.log(`WROTE ${picked.length} cookies -> ${outPath}`);
console.log('NAMES: ' + picked.map(c => c.name).join(', '));
ws.close();
